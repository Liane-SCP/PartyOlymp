export function normalizePhotoSubject(subject) {
  const answer = names[subject.answer] || subject.answer;
  return {
    ...subject,
    answer,
    aliases: correctedAliases[subject.answer] || [
      ...new Set(
        [
          answer,
          subject.answer,
          ...subject.aliases,
          ...(aliases[subject.answer] || []),
        ].filter((value) => value !== "Pokals"),
      ),
    ],
  };
}

